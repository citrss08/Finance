// ---------- CUSTOM CANVAS GRAPHS (NO EXTERNAL CHART PACKAGE) ----------

const graphPalette = {

  coral: "#d98573",

  sage: "#82998a",

  slate: "#77828b",

  grid: "#e7ebe8",

  text: "#77817b"

};


function canvasContext(id, height = 250) {

  const canvas = $(id);

  if (!canvas) return null;


  const width = canvas.clientWidth;

  if (width < 20) return null;


  const ratio = Math.max(
    1,
    window.devicePixelRatio || 1
  );


  canvas.width = Math.round(width * ratio);

  canvas.height = Math.round(height * ratio);


  const ctx = canvas.getContext("2d");

  ctx.setTransform(ratio, 0, 0, ratio, 0, 0);

  ctx.clearRect(0, 0, width, height);


  return {
    canvas,
    ctx,
    width,
    height
  };

}


function niceMax(value) {

  if (value <= 0) return 1;


  const magnitude = Math.pow(
    10,
    Math.floor(Math.log10(value))
  );


  return Math.ceil(
    value / magnitude * 1.12
  ) * magnitude;

}


// LINE GRAPH

function drawLineChart(
  id,
  labels,
  series,
  height = 250
) {

  const state = canvasContext(id, height);

  if (!state) return;


  const { ctx, width, height: h } = state;


  const margin = {
    top: 18,
    right: 18,
    bottom: 42,
    left: 64
  };


  const plotW =
    width - margin.left - margin.right;

  const plotH =
    h - margin.top - margin.bottom;


  const all =
    series.flatMap(s => s.values);


  let min = Math.min(0, ...all);

  let max = niceMax(Math.max(1, ...all));


  if (min < 0) {
    min = -niceMax(Math.abs(min)) / 1.12;
  }


  const range = max - min || 1;


  const x = i =>

    margin.left +

    (
      labels.length <= 1
        ? 0
        : i * plotW / (labels.length - 1)
    );


  const y = value =>

    margin.top +

    (max - value) / range * plotH;


  ctx.font = "10px DM Sans, sans-serif";

  ctx.textAlign = "right";

  ctx.textBaseline = "middle";


  // Horizontal grid lines

  for (let step = 0; step <= 4; step++) {

    const value =
      max - step * range / 4;

    const py = y(value);


    ctx.strokeStyle = graphPalette.grid;

    ctx.lineWidth = 1;

    ctx.beginPath();

    ctx.moveTo(margin.left, py);

    ctx.lineTo(width - margin.right, py);

    ctx.stroke();


    ctx.fillStyle = graphPalette.text;

    ctx.fillText(
      compactAmount(value),
      margin.left - 9,
      py
    );

  }


  // X-axis labels

  ctx.textAlign = "center";

  ctx.textBaseline = "top";


  labels.forEach((label, i) => {

    ctx.fillStyle = graphPalette.text;

    ctx.fillText(
      label,
      x(i),
      h - margin.bottom + 12
    );

  });


  // Plot each data series

  series.forEach(s => {

    ctx.strokeStyle = s.color;

    ctx.lineWidth = 2.5;

    ctx.lineJoin = "round";

    ctx.lineCap = "round";

    ctx.beginPath();


    s.values.forEach((value, i) => {

      if (i === 0) {

        ctx.moveTo(x(i), y(value));

      } else {

        ctx.lineTo(x(i), y(value));

      }

    });


    ctx.stroke();


    // Point markers

    s.values.forEach((value, i) => {

      ctx.fillStyle = "#ffffff";

      ctx.strokeStyle = s.color;

      ctx.lineWidth = 2;

      ctx.beginPath();

      ctx.arc(
        x(i),
        y(value),
        3,
        0,
        Math.PI * 2
      );

      ctx.fill();

      ctx.stroke();

    });

  });


  // Legend

  let legendX = margin.left;

  const legendY = h - 12;


  ctx.font = "10px DM Sans, sans-serif";

  ctx.textAlign = "left";


  series.forEach(s => {

    ctx.fillStyle = s.color;

    ctx.fillRect(
      legendX,
      legendY - 6,
      15,
      3
    );


    ctx.fillStyle = graphPalette.text;

    ctx.fillText(
      s.name,
      legendX + 21,
      legendY - 11
    );


    legendX +=
      ctx.measureText(s.name).width + 46;

  });

}


// BAR GRAPH

function drawBarChart(
  id,
  labels,
  values,
  colors,
  height = 220
) {

  const state = canvasContext(id, height);

  if (!state) return;


  const { ctx, width, height: h } = state;


  const margin = {
    top: 20,
    right: 18,
    bottom: 40,
    left: 62
  };


  const plotW =
    width - margin.left - margin.right;

  const plotH =
    h - margin.top - margin.bottom;


  const max =
    niceMax(Math.max(...values, 1));


  ctx.font = "10px DM Sans, sans-serif";

  ctx.textAlign = "right";

  ctx.textBaseline = "middle";


  // Grid lines

  for (let step = 0; step <= 4; step++) {

    const value =
      max - step * max / 4;

    const y =
      margin.top + step * plotH / 4;


    ctx.strokeStyle = graphPalette.grid;

    ctx.beginPath();

    ctx.moveTo(margin.left, y);

    ctx.lineTo(width - margin.right, y);

    ctx.stroke();


    ctx.fillStyle = graphPalette.text;

    ctx.fillText(
      compactAmount(value),
      margin.left - 8,
      y
    );

  }


  const slot = plotW / labels.length;

  const barW = Math.min(70, slot * .48);


  // Bars

  values.forEach((value, i) => {

    const bh = value / max * plotH;


    const x =
      margin.left +
      slot * i +
      (slot - barW) / 2;


    const y =
      margin.top + plotH - bh;


    ctx.fillStyle = colors[i];

    ctx.beginPath();


    if (ctx.roundRect) {

      ctx.roundRect(
        x,
        y,
        barW,
        bh,
        5
      );

    } else {

      ctx.rect(
        x,
        y,
        barW,
        bh
      );

    }


    ctx.fill();


    ctx.fillStyle = graphPalette.text;

    ctx.textAlign = "center";

    ctx.textBaseline = "top";

    ctx.fillText(
      labels[i],
      x + barW / 2,
      h - margin.bottom + 12
    );

  });

}


// SHORTEN LARGE NUMBERS ON GRAPH AXES

function compactAmount(value) {

  const abs = Math.abs(value);

  const sign = value < 0 ? "−" : "";


  if (abs >= 1000000) {

    return `${sign}${(abs / 1000000).toFixed(1)}m`;

  }


  if (abs >= 1000) {

    return `${sign}${(abs / 1000).toFixed(0)}k`;

  }


  return `${sign}${abs.toFixed(0)}`;

}


